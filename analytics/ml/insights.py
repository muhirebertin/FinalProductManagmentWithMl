"""
Descriptive analytics used by the dashboard and the API:
KPIs, monthly production trend, delay rate per category, and the
material demand forecast generated by AI-scored incoming orders.
"""
import datetime as dt
from collections import defaultdict

from django.db.models import Avg, Count, F as DbF, Q, Sum  # noqa: F401
from django.db.models.functions import TruncMonth
from django.utils import timezone

from inventory.models import RawMaterial


def inventory_value():
    total = 0.0
    for qty, cost in RawMaterial.objects.values_list("quantity_in_stock", "unit_cost"):
        total += float(qty or 0) * float(cost or 0)
    return round(total, 0)


def history_kpis():
    from analytics.models import IncomingOrder, PredictionLog, ProductionRecord
    agg = ProductionRecord.objects.aggregate(
        n=Count("id"), delayed=Count("id", filter=Q(delayed=True)),
        units=Sum("quantity"), defects=Sum("defective_units"), avg_days=Avg("actual_days"))
    n = agg["n"] or 0
    since = timezone.localdate() - dt.timedelta(days=90)
    recent = ProductionRecord.objects.filter(end_date__gte=since).aggregate(
        n=Count("id"), delayed=Count("id", filter=Q(delayed=True)))
    today = timezone.localdate()
    return {
        "records": n,
        "on_time_rate": round(100.0 * (n - agg["delayed"]) / n, 1) if n else None,
        "on_time_rate_90d": round(100.0 * (recent["n"] - recent["delayed"]) / recent["n"], 1) if recent["n"] else None,
        "units_produced": agg["units"] or 0,
        "defect_rate": round(100.0 * (agg["defects"] or 0) / agg["units"], 2) if agg["units"] else None,
        "avg_days": round(agg["avg_days"] or 0, 1),
        "orders_today": IncomingOrder.objects.filter(received_at__date=today).count(),
        "orders_open": IncomingOrder.objects.filter(status="New").count(),
        "orders_high_risk": IncomingOrder.objects.filter(status="New", risk_level="High").count(),
        "predictions_served": PredictionLog.objects.count(),
        "sources": dict(ProductionRecord.objects.values_list("source").annotate(c=Count("id")).values_list("source", "c")),
    }


def monthly_trend(months=12):
    from analytics.models import ProductionRecord
    start = (timezone.localdate().replace(day=1) - dt.timedelta(days=31 * (months - 1))).replace(day=1)
    rows = (ProductionRecord.objects.filter(end_date__gte=start)
            .annotate(m=TruncMonth("end_date")).values("m")
            .annotate(units=Sum("quantity"), batches=Count("id"),
                      delayed=Count("id", filter=Q(delayed=True)), defects=Sum("defective_units"))
            .order_by("m"))
    by_month = {r["m"].strftime("%Y-%m") if hasattr(r["m"], "strftime") else str(r["m"])[:7]: r for r in rows}
    labels, units, delay_rate, batches = [], [], [], []
    cursor = start
    for _ in range(months):
        key = cursor.strftime("%Y-%m")
        r = by_month.get(key)
        labels.append(cursor.strftime("%b %Y"))
        units.append(int(r["units"]) if r else 0)
        batches.append(int(r["batches"]) if r else 0)
        delay_rate.append(round(100.0 * r["delayed"] / r["batches"], 1) if r and r["batches"] else 0)
        cursor = (cursor + dt.timedelta(days=32)).replace(day=1)
    return {"labels": labels, "units": units, "batches": batches, "delay_rate": delay_rate}


def category_delay():
    from analytics.models import ProductionRecord
    rows = (ProductionRecord.objects.values("category")
            .annotate(n=Count("id"), delayed=Count("id", filter=Q(delayed=True)), avg_days=Avg("actual_days"))
            .order_by("category"))
    return [{"category": r["category"], "batches": r["n"],
             "delay_rate": round(100.0 * r["delayed"] / r["n"], 1) if r["n"] else 0,
             "avg_days": round(r["avg_days"] or 0, 1)} for r in rows]


def task_status_breakdown():
    from production.models import ProductionTask
    counts = dict(ProductionTask.objects.values_list("status").annotate(c=Count("id")).values_list("status", "c"))
    labels = ["Pending", "In Progress", "Completed"]
    return {"labels": labels, "values": [counts.get(s, 0) for s in labels]}


def material_demand_forecast():
    """
    Forward-looking stock check: what happens to the warehouse if every NEW
    incoming order (scored but not yet converted) is accepted?
    """
    from analytics.models import IncomingOrder
    demand = defaultdict(float)
    orders = IncomingOrder.objects.filter(status="New").select_related("product").prefetch_related(
        "product__bom_items__material")
    for order in orders:
        if not order.product:
            continue
        for bom in order.product.bom_items.all():
            demand[bom.material_id] += float(bom.quantity_per_unit) * order.quantity
    result = []
    for m in RawMaterial.objects.all().order_by("name"):
        stock = float(m.quantity_in_stock)
        need = round(demand.get(m.pk, 0.0), 2)
        projected = round(stock - need, 2)
        if projected < 0:
            status = "shortage"
        elif projected <= float(m.reorder_level):
            status = "reorder"
        else:
            status = "ok"
        coverage = round(100.0 * stock / need, 0) if need else None
        result.append({"id": m.pk, "code": m.code, "name": m.name, "unit": m.unit, "stock": round(stock, 2),
                       "reorder_level": float(m.reorder_level), "pending_demand": need,
                       "projected_stock": projected, "coverage_pct": coverage, "status": status})
    order = {"shortage": 0, "reorder": 1, "ok": 2}
    result.sort(key=lambda r: (order[r["status"]], -(r["pending_demand"])))
    return result


def low_stock_count():
    return RawMaterial.objects.filter(quantity_in_stock__lte=DbF("reorder_level")).count()
